impl HasChildren for Node {
    fn children(&self) -> Vec<ChildRef<'_>> {
        macro_rules! dispatch {
            ($($variant:ident),* $(,)?) => {
                match self {
                    $(Node::$variant(c) => <_ as HasChildren>::children(c)),*
                }
            };
        }
        dispatch!(
            Program,
            BlockStatements,
            LocalVariableDeclarationStatement,
            ThrowStatement,
            WhileStatement,
            TraditionalForStatement,
            ForEachStatement,
            FunctionStatement,
            MacroStatement,
            BreakContinueStatement,
            ReturnStatement,
            EmptyStatement,
            ExpressionStatement,
            NonExpressionStatement,
            LocalVariableDeclaration,
            ForInit,
            VariableDeclaratorList,
            VariableDeclarator,
            VariableDeclaratorId,
            VariableInitializer,
            ArrayInitializer,
            VariableInitializerList,
            DeclType,
            DeclTypeNoArr,
            PrimitiveType,
            ClsType,
            Dims,
            DimExprs,
            Expression,
            LeftHandSide,
            AssignOperator,
            TernaryExpr,
            BaseExpr,
            LeftAsso,
            Binaryop,
            Primary,
            PrefixExpress,
            SuffixExpress,
            ConstExpr,
            CastExpr,
            GroupExpr,
            NewObjExpr,
            NewEmptyArrExpr,
            NewInitArrExpr,
            VarIdExpr,
            TypeExpr,
            ListExpr,
            ListItems,
            MapExpr,
            BlockExpr,
            ContextSelectExpr,
            QlIf,
            ThenBody,
            ElseBody,
            SwitchExpr,
            SwitchCaseGroups,
            SwitchStatementGroup,
            SwitchExprGroup,
            SwitchLabels,
            SwitchLabel,
            SwitchExpressionLabel,
            ExpressionList,
            TryCatchExpr,
            TryCatches,
            TryCatch,
            CatchParams,
            TryFinally,
            MapEntries,
            MapEntry,
            ClsValue,
            EValue,
            IdKey,
            StringKey,
            QuoteStringKey,
            MethodInvoke,
            FieldAccess,
            MethodAccess,
            IndexExpr,
            CustomPath,
            FieldId,
            SingleIndex,
            SliceIndex,
            ArgumentList,
            Literal,
            DoubleQuoteStringLiteral,
            StringExpression,
            BoolenLiteral,
            LambdaExpr,
            LambdaParameters,
            FormalOrInferredParameterList,
            FormalOrInferredParameter,
            ImportCls,
            ImportPack,
            OpId,
            VarId
        )
    }
}
